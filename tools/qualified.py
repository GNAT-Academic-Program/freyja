GENERIC = {'Device:R', 'Device:C', 'Device:L', 'Device:Polyfuse'}


def lookup(ref, lib_id):
    return PARTS.get(ref) or PARTS.get(lib_id)


def check(parts):
    """Raise unless every non-generic part is qualified and fitted as stated."""
    bad = []
    for p in parts:
        if (p['lib_id'] in GENERIC or p['lib_id'] in HEADER_SYMS) and p['ref'] not in PARTS:
            continue
        q = lookup(p['ref'], p['lib_id'])
        if q is None:
            bad.append(f"{p['ref']} ({p['lib_id']}) has no entry in "
                       f"tools/qualified.py")
        elif q['fp'] != p['fp']:
            bad.append(f"{p['ref']} is fitted {p['fp']!r} but qualified as "
                       f"{q['fp']!r}")
    if bad:
        raise ValueError('unqualified parts:\n  ' + '\n  '.join(bad))
    return len([p for p in parts if (p['lib_id'] not in GENERIC
                and p['lib_id'] not in HEADER_SYMS) or p['ref'] in PARTS])


HEAD = """# Qualified parts

**Generated by `tools/qualified.py`. Do not hand-edit.**

A footprint that matches its symbol's `ki_fp_filters` is not a qualified part.
The filter can be missing, or broad enough to admit the wrong package, and it
knows nothing about whether the part survives the voltage on the net it is
soldered to. This page is the stronger claim, and `tools/design.py` will not
build if a part here is fitted with a different footprint, or if a non-generic
part is missing from it altogether.

`NOT SELECTED` and `ASSUMED` mean exactly that. Those rows are the open work.

Ordinary passives are not listed individually. Resistors and capacitors are
0402 or 0603; what matters about them is voltage rating and dielectric, which
is [`ref/power-budget.md`](power-budget.md) and `findings.md` item 13.
Inductors *are* qualified, per rail, in
[`ref/power-budget.md`](power-budget.md) -- the requirement is computed there,
so the part is named there.

| Designator(s) | MPN | Package | Footprint | Ratings that matter here | Pin map | Source |
|---|---|---|---|---|---|---|
"""


def table(parts):
    rows, bykey = [], {}
    for p in parts:
        if (p['lib_id'] in GENERIC or p['lib_id'] in HEADER_SYMS) and p['ref'] not in PARTS:
            continue
        key = p['ref'] if p['ref'] in PARTS else p['lib_id']
        bykey.setdefault(key, []).append(p['ref'])
    for key, refs in bykey.items():
        q = PARTS[key]
        r = ', '.join(f'`{x}`' for x in refs)
        rows.append(f"| {r} | **{q['mpn']}** | {q['pkg']} | `{q['fp']}` | "
                    f"{q['rating']} | {q['pinmap']} | {q['src']} |")
    return rows


def main():
    sys.path.insert(0, __file__.rsplit('/', 1)[0])
    from design import build
    parts = build().parts
    n = check(parts)
    rows = table(parts)
    print(f"{n} non-generic parts, all qualified, in {len(rows)} entries")
    for r in rows:
        print('  ' + r.split('|')[1].strip() + ' -> ' + r.split('|')[2].strip())
    if '--write' in sys.argv:
        open('ref/qualified-parts.md', 'w').write(HEAD + '\n'.join(rows) + '\n')
        print('wrote ref/qualified-parts.md')
    return 0


if __name__ == '__main__':
    sys.exit(main())
