#!/usr/bin/env python3
"""JLCPCB assembly BOM from tools/design.py, and the pre-order list.

    python3 tools/bom_jlc.py            # print both tables
    python3 tools/bom_jlc.py --write    # ref/bom-jlcpcb.csv, ref/preorder.md

The CSV has JLCPCB's four columns (Comment, Designator, Footprint, LCSC
Part), one row per identical part (same value, footprint and LCSC
number), designators comma-separated. Parts marked DNP are left out.
Passives without an LCSC number keep an empty LCSC column, for JLCPCB's
matcher to propose a same-value part at order time (kicad/README.md).

The pre-order list names the lines that are not in the JLCPCB assembly
library and have to be bought from LCSC into the JLCPCB parts inventory
before the order, with the quantity for BOARDS boards plus attrition.
Membership is the owner's part-availability audit of 2026-10-30 (the
decisions of its steps 16 and 17); it is data here, not a library query.
"""
import csv, io, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from design import build

BOARDS = 10
# LCSC number -> (why it is a pre-order, attrition pieces for BOARDS boards)
PREORDER = {
    'C1521803': ('XC7A100T-2FGG676I, U1: not in the JLCPCB library (decision 16 '
                 'pending: pre-order, or the FGG484 C410276 in the library)', 1),
    'C5360304': ('APS6404L-SQN-SN, U2-U5: no 1.8 V SOP-8 PSRAM in the library '
                 '(decision 17 pending: pre-order, or the 3 V APS1604M C18214056)', 4),
}


def rows():
    parts = [p for p in build().parts if not p.get('dnp')]
    groups = {}
    for p in parts:
        key = (p['value'], p['fp'], p['lcsc'])
        groups.setdefault(key, []).append(p['ref'])
    def natural(r):
        import re
        m = re.match(r'([A-Z]+)(\d+)([A-Z]?)', r)
        return (m.group(1), int(m.group(2)), m.group(3))
    out = []
    for (value, fp, lcsc), refs in groups.items():
        refs = sorted(refs, key=natural)
        out.append((value, ','.join(refs), fp.split(':', 1)[-1], lcsc, len(refs)))
    out.sort(key=lambda r: natural(r[1].split(',')[0]))
    return out


def csv_text(table):
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator='\n')
    w.writerow(['Comment', 'Designator', 'Footprint', 'LCSC Part'])
    for value, refs, fp, lcsc, _n in table:
        w.writerow([value, refs, fp, lcsc])
    return buf.getvalue()


def preorder_text(table):
    lines = ['# Pre-order list (LCSC into the JLCPCB parts inventory)', '',
             f'For {BOARDS} boards. Generated by `tools/bom_jlc.py` from the fitted design; '
             'the membership is the open decisions of the 2026-10-30 availability audit.', '',
             '| LCSC | Part | Designators | Per board | Order | Why |', '|---|---|---|---:|---:|---|']
    for value, refs, fp, lcsc, n in table:
        if lcsc in PREORDER:
            why, extra = PREORDER[lcsc]
            lines.append(f'| {lcsc} | {value} | {refs} | {n} | {n * BOARDS + extra} | {why} |')
    lines += ['', 'Every other line of `ref/bom-jlcpcb.csv` is in the JLCPCB assembly library '
              '(the 13 replacements of the audit are fitted; stock as of the audit, re-check at order time).']
    return '\n'.join(lines) + '\n'


def main():
    table = rows()
    text = csv_text(table)
    pre = preorder_text(table)
    with_lcsc = sum(1 for r in table if r[3])
    print(f'{len(table)} BOM lines for {sum(r[4] for r in table)} fitted parts, '
          f'{with_lcsc} lines with an LCSC number, {sum(1 for r in table if r[3] in PREORDER)} pre-order lines')
    if '--write' in sys.argv:
        open('ref/bom-jlcpcb.csv', 'w').write(text)
        open('ref/preorder.md', 'w').write(pre)
        print('wrote ref/bom-jlcpcb.csv and ref/preorder.md')
    else:
        print(text[:1500]); print(pre)


if __name__ == '__main__':
    main()
