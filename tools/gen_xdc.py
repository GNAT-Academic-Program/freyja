#!/usr/bin/env python3
"""Render the board constraints and the Vivado gate's top level from
tools/alloc.py, the one place ball allocation is decided.

    python3 tools/gen_xdc.py          # writes ref/freya.xdc, gateware/gate/top.v

ref/freya.xdc is the board file every gateware project starts from: one
PACKAGE_PIN and IOSTANDARD per allocated ball, the input clocks, and the
SPIx4 configuration properties. gateware/gate/top.v is a throwaway design
that touches every one of those ports, so `vivado -source gateware/gate/run.tcl`
proves the allocation is legal (banks, clock-capable balls, LVDS pairs,
IOSTANDARD mixing) all the way to a bitstream. Timing exceptions that belong
to the gate alone live in gateware/gate/gate.xdc, not here.
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from alloc import assign, SYS_CLK
from identity import FPGA_PART, PRODUCT, HW_VERSION

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
XDC = os.path.join(ROOT, 'ref', 'freya.xdc')
TOP = os.path.join(ROOT, 'gateware', 'gate', 'top.v')
# XC7A100T-2FGG676I: Vivado names the device/package/speed; the temperature
# grade is a device property, not part of the part name.
PART = 'xc7a100tfgg676-2'

# Bank -> VCCO -> single-ended standard. Banks 15 and 34 follow the J19/J20
# jumpers; the file assumes the 3.3 V position, change both lines together.
# Bank 13 is +1V8_IO (gen_sch.RAIL): the PSRAMs and the translators' A side.
VCCO_STD = {'13': 'LVCMOS18', '14': 'LVCMOS33', '15': 'LVCMOS33',
            '34': 'LVCMOS33', '16': 'LVCMOS25', '35': 'LVCMOS33'}
# Input clocks: net -> (period ns, note)
CLOCKS = {SYS_CLK: (20.0, 'X4, 50 MHz CMOS oscillator'),
          'PHY_RXC': (8.0, 'RTL8211FD-CG RXC at 1000 Mb/s, 2 ns RXDLY inside the PHY'),
          'LINK_P_RXC_P': (10.0, 'LINK P receive clock, 100 MHz placeholder until characterised'),
          'LINK_Q_RXC_P': (10.0, 'LINK Q receive clock, 100 MHz placeholder until characterised')}


def direction(net):
    """in / out / inout as the board sees the FPGA pin."""
    if net == SYS_CLK or re.match(r'PHY_(RXC|RXD\d|RX_CTL|INT_N)$|LINK_[PQ]_RX[CD]_[PN]$'
                                  r'|SB_UART_RX$|DBG_T(CK|MS|DI)$|PUDC_B$|HDMI_HPD$|MRAM_SO$'
                                  r'|SD_(MISO|CD)$', net):
        return 'in'
    if re.match(r'PHY_(TXC|TXD\d|TX_CTL|MDC|RESET_N)$|LINK_[PQ]_TX[CD]_[PN]$|SB_UART_TX$'
                r'|DBG_TDO$|BUS5V\d_(DIR|OE_N)$|HDMI_(CLK|D\d)_[PN]$|HDMI_(CT_HPD|LS_OE)$'
                r'|SDRAM_(A\d+|BA\d|CLK|CKE|CS_N|RAS_N|CAS_N|WE_N|LDQM|UDQM)$'
                r'|MRAM_(CS|SCK|SI)$|SD_(CS|SCK|MOSI)$', net):
        return 'out'
    if re.match(r'SLOT[A-H]_IO\d+$|BUS5V\d_IO\d$|PHY_MDIO$|FLASH_|PSRAM\d_|HDMI_(SCL|SDA|CEC)$'
                r'|SDRAM_DQ\d+$', net):
        return 'inout'
    raise ValueError(f'no direction rule for {net}')


def group_of(net):
    """Section a net belongs to in the XDC. SDRAM_CLK is a forwarded clock
    and gets a section of its own, so a design can set its ODDR, slew and
    drive without touching the bus."""
    if net == 'SDRAM_CLK': return 'SDRAM_CLK'
    return re.sub(r'\d+$|_[PN]$', '', net).split('_')[0]


def bank_of(name):
    return re.search(r'_(\d+)$', name).group(1)


def rows():
    net, _psram, _sb, _slots, io, _other = assign()
    names = {b: n for lst in io.values() for b, n in lst}
    out = []
    for ball, n in sorted(net.items(), key=lambda t: (group_of(t[1]), t[1])):
        bank = bank_of(names[ball])
        if n.startswith('LINK_'):
            std = 'LVDS_25'
        elif re.match(r'HDMI_(CLK|D\d)_[PN]$', n):
            std = 'TMDS_33'               # UG471: 3.3 V VCCO, 50 ohm to 3.3 V at the sink
        else:
            std = VCCO_STD[bank]
        out.append(dict(net=n, ball=ball, bank=bank, std=std, pkg=names[ball],
                        dir=direction(n)))
    return out


def xdc(rs):
    o = [f'# {PRODUCT} {HW_VERSION} board constraints for {FPGA_PART}',
         '# Generated by tools/gen_xdc.py from tools/alloc.py. Do not hand-edit.',
         '# Ball allocation: ref/ballmap.md. Banks 15 and 34 are assumed at the',
         '# 3.3 V jumper position (J19/J20); edit VCCO_STD in the generator otherwise.',
         '',
         '# ---- configuration: master SPI x4 from the W25Q256 (UG470 ch. 2)',
         'set_property CFGBVS VCCO [current_design]',
         'set_property CONFIG_VOLTAGE 3.3 [current_design]',
         'set_property CONFIG_MODE SPIx4 [current_design]',
         'set_property BITSTREAM.CONFIG.SPI_BUSWIDTH 4 [current_design]',
         'set_property BITSTREAM.CONFIG.CONFIGRATE 33 [current_design]',
         'set_property BITSTREAM.GENERAL.COMPRESS TRUE [current_design]',
         '']
    last = None
    for r in rs:
        grp = group_of(r['net'])
        if grp != last:
            if grp == 'SDRAM_CLK':
                o.append('# ---- SDRAM_CLK: forwarded clock, 22 ohm series at the FPGA. Drive it')
                o.append('# from an ODDR; set its slew and drive here, apart from the bus.')
            else:
                o.append(f'# ---- {grp}')
            last = grp
        o.append(f"set_property -dict {{PACKAGE_PIN {r['ball']} IOSTANDARD {r['std']}}} "
                 f"[get_ports {{{r['net']}}}]   ;# bank {r['bank']} {r['pkg']}")
        if r['std'] == 'LVDS_25' and r['dir'] == 'in':
            o.append(f"set_property DIFF_TERM TRUE [get_ports {{{r['net']}}}]")
        if re.match(r'PHY_(TXC|TXD\d|TX_CTL)$|SDRAM_CLK$', r['net']):
            o.append(f"set_property SLEW FAST [get_ports {{{r['net']}}}]")
        if r['net'] == 'SD_CD':
            o.append(f"set_property PULLUP TRUE [get_ports {{{r['net']}}}]   ;# detect switch to the shell, no board pull-up")
    o.append('')
    o.append('# ---- input clocks')
    for n, (period, note) in CLOCKS.items():
        o.append(f'create_clock -period {period:.3f} -name {n.lower()} [get_ports {{{n}}}]   ;# {note}')
    return '\n'.join(o) + '\n'


def verilog(rs):
    """Every port used: inputs fold into a register, outputs come from a
    counter, inouts get an IOBUF, LVDS pairs real differential buffers."""
    DIFF = ('LVDS_25', 'TMDS_33')
    ins = [r for r in rs if r['dir'] == 'in' and r['std'] not in DIFF]
    outs = [r for r in rs if r['dir'] == 'out' and r['std'] not in DIFF]
    ios = [r for r in rs if r['dir'] == 'inout']
    lv_in = sorted({r['net'][:-2] for r in rs if r['std'] == 'LVDS_25' and r['dir'] == 'in'})
    lv_out = sorted({(r['net'][:-2], r['std']) for r in rs if r['std'] in DIFF and r['dir'] == 'out'})
    ports = []
    for r in rs:
        kw = {'in': 'input', 'out': 'output', 'inout': 'inout'}[r['dir']]
        ports.append(f"    {kw:6s} {r['net']}")
    o = ['// Generated by tools/gen_xdc.py. Vivado gate for ref/freya.xdc: every',
         '// allocated ball is a used port, so place/route and bitstream generation',
         '// exercise the whole allocation. Not a product design.',
         '`timescale 1ns / 1ps',
         'module top (', ',\n'.join(ports), ');',
         '    wire clk;',
         f'    BUFG bufg_sys (.I({SYS_CLK}), .O(clk));',
         '    reg [27:0] cnt = 0;',
         '    always @(posedge clk) cnt <= cnt + 1;',
         '    // RGMII receive clock: its own BUFG and counter, so the MRCC ball',
         '    // and a second global clock are exercised.',
         '    wire rxc;',
         '    BUFG bufg_rxc (.I(PHY_RXC), .O(rxc));',
         '    reg [7:0] rxcnt = 0;',
         '    always @(posedge rxc) rxcnt <= rxcnt + 1;']
    # inputs fold
    fold = ' ^ '.join(r['net'] for r in ins if r['net'] not in (SYS_CLK, 'PHY_RXC'))
    o += ['    reg fold = 0;', f'    always @(posedge clk) fold <= {fold} ^ rxcnt[7];']
    # LVDS receive pairs: IBUFDS, the clocks through BUFR-capable paths
    for i, base in enumerate(lv_in):
        o.append(f'    wire {base.lower()};')
        o.append(f'    IBUFDS #(.DIFF_TERM("TRUE"), .IOSTANDARD("LVDS_25")) ib_{i} '
                 f'(.I({base}_P), .IB({base}_N), .O({base.lower()}));')
    for base in lv_in:
        if base.endswith('RXC'):
            o += [f'    wire {base.lower()}_g;',
                  f'    BUFG bufg_{base.lower()} (.I({base.lower()}), .O({base.lower()}_g));',
                  f'    reg [3:0] {base.lower()}_cnt = 0;',
                  f'    always @(posedge {base.lower()}_g) {base.lower()}_cnt <= {base.lower()}_cnt + 1;']
    data_in = [b.lower() for b in lv_in if not b.endswith('RXC')]
    clk_in = [b.lower() + '_cnt[3]' for b in lv_in if b.endswith('RXC')]
    o += ['    reg lvfold = 0;',
          f"    always @(posedge clk) lvfold <= {' ^ '.join(data_in + clk_in)};"]
    # inouts through IOBUF, tristate from the counter
    for i, r in enumerate(ios):
        o.append(f"    wire io_{i};")
        o.append(f"    IOBUF iob_{i} (.I(cnt[{i % 20}]), .T(cnt[{20 + i % 8}]), .O(io_{i}), .IO({r['net']}));")
    if ios:
        o += ['    reg iofold = 0;',
              f"    always @(posedge clk) iofold <= {' ^ '.join(f'io_{i}' for i in range(len(ios)))};"]
    # outputs from the counter
    for i, r in enumerate(outs):
        o.append(f"    assign {r['net']} = cnt[{i % 20}] ^ fold ^ lvfold ^ iofold;")
    # LVDS transmit pairs
    for i, (base, std) in enumerate(lv_out):
        o.append(f'    OBUFDS #(.IOSTANDARD("{std}")) ob_{i} '
                 f'(.I(cnt[{(i + 3) % 20}] ^ fold), .O({base}_P), .OB({base}_N));')
    o.append('endmodule')
    return '\n'.join(o) + '\n'


def main():
    rs = rows()
    os.makedirs(os.path.dirname(TOP), exist_ok=True)
    open(XDC, 'w').write(xdc(rs))
    open(TOP, 'w').write(verilog(rs))
    by = {}
    for r in rs: by.setdefault((r['bank'], r['std']), 0); by[(r['bank'], r['std'])] += 1
    print(f'{len(rs)} constrained balls -> {os.path.relpath(XDC, ROOT)}, {os.path.relpath(TOP, ROOT)}')
    for (bank, std), n in sorted(by.items()): print(f'  bank {bank:3s} {std:9s} {n}')
    print(f'part {PART}; clocks: ' + ', '.join(CLOCKS))


if __name__ == '__main__':
    main()
