#!/usr/bin/env python3
"""Render ref/ballmap.md from tools/alloc.py — the single allocation source.
    python3 tools/ballmap.py > ref/ballmap.md
Package facts come from the imported EasyEDA/LCSC symbol."""
import sys, os, re
sys.path.insert(0, os.path.dirname(__file__))
from alloc import assign, load, pairs_and_singles, CONFIG_USE, SIDEBAND
from collections import defaultdict

def main():
    net, psram, sb, slots, io, other = assign()
    tot = sum(len(v) for v in io.values())
    o = []; W = o.append

    W("# XC7A100T-FGG676 ball map\n")
    W("Generated by `tools/ballmap.py` from `tools/alloc.py`, which is the one")
    W("place ball allocation is decided. The schematic is generated from the same")
    W("function, so this file and the circuit cannot disagree. Package facts come")
    W("from the imported `XC7A100T-2FGG676I` symbol, LCSC `C1521803`.\n")
    W("```\npython3 tools/ballmap.py > ref/ballmap.md\n```\n")

    W("## I/O-bank architecture\n")
    W(f"This package has **six HR I/O banks** — 13, 14, 15, 16, 34 and 35 — {tot} user I/O total.")
    W("`VCCO` is shared by every pin in a bank. Odin uses bank 13 at 1.8V (+1V8_IO)")
    W("for the four PSRAMs and the A side of both 5V bus translators, bank 14 at")
    W("fixed 3.3V, banks 15 and 34 as selectable extension domains, bank 16 at")
    W("2.5V for the network (RGMII and the two LVDS link ports), and bank 35 at")
    W("3.3V for HDMI, the SDRAM data bus and the PHY control pins.\n")
    W("| Bank | HR I/O | Diff pairs | MRCC | SRCC |")
    W("|---|---|---|---|---|")
    for bk in ('13', '14', '15', '16', '34', '35'):
        fp, _ = pairs_and_singles(io[bk])
        mr = sum('MRCC' in n for _, n in io[bk]); sr = sum('SRCC' in n for _, n in io[bk])
        W(f"| {bk} | {len(io[bk])} | {len(fp)} | {mr} | {sr} |")
    W("")
    W("**Bank 14 is not free.** It carries the master-SPI config flash pins and the")
    W("`PUDC_B` strap, so its `VCCO` is pinned at 3.3V by the flash. It also carries")
    W("the supervisor sideband, the fabric clock, the SDRAM address bus, the MRAM")
    W("and the microSD socket. Bank 13 runs at 1.8V from +1V8_IO: the four")
    W("APS6404L-SQN PSRAMs and both 5V bus translators (their A side and DIR/OE).")
    W("Banks 15 and 34 are the two settable extension domains, four slots each.")
    W("Bank 16 runs at 2.5V: RGMII to the RTL8211FD-CG and the eight LVDS_25 link")
    W("pairs. Bank 35 is at 3.3V: HDMI, the SDRAM data and control lines, and the")
    W("two PHY control pins (PHYRSTB, INTB). The PSRAM, SDRAM, MRAM, microSD and")
    W("PHY control balls are hand-chosen tables in tools/alloc.py; inside each")
    W("bank the allocator takes the shallowest balls first for the rest.\n")

    W("## Allocation\n")
    W("| Bank | VCCO | Contents |")
    W("|---|---|---|")
    W("| 14 | **fixed 3.3V** | SYS_CLK (50 MHz oscillator), config flash, supervisor sideband, SDRAM address, MRAM, microSD |")
    W("| 13 | **fixed 1.8V** (+1V8_IO) | PSRAM x4, 5V BUS 0, 5V BUS 1 |")
    W("| 15 | **settable** 3.3 / 2.5 / 1.8 | slots A B C D |")
    W("| 34 | **settable** 3.3 / 2.5 / 1.8 | slots E F G H |")
    W("| 16 | **fixed 2.5V** | RGMII + MDIO to the PHY, LINK P and LINK Q |")
    W("| 35 | fixed 3.3V | HDMI out: four TMDS_33 pairs and the TPD12S016 lines; SDRAM data and control; PHY_RESET_N, PHY_INT_N |")
    W("")

    names = {b: n for lst in list(io.values()) + list(other.values()) for b, n in lst}
    groups = defaultdict(list)
    for ball, n in sorted(net.items()):
        if n.startswith('SLOT') and '_DIR' not in n: groups['slots'].append((ball, n))
        elif n.startswith('BUS5V') and n.endswith('_DIR'): groups['5V bus direction'].append((ball, n))
        elif n.startswith('BUS5V') and n.endswith('_OE_N'): groups['5V bus enable'].append((ball, n))
        elif n.startswith('BUS5V'): groups['5V bus data'].append((ball, n))
        elif n.startswith('PSRAM'): groups['PSRAM'].append((ball, n))
        elif n.startswith('SDRAM_'): groups['SDRAM'].append((ball, n))
        elif n.startswith('MRAM_'): groups['MRAM'].append((ball, n))
        elif n.startswith('SD_'): groups['microSD'].append((ball, n))
        elif n in CONFIG_USE.values(): groups['config flash + strap'].append((ball, n))
        elif n in SIDEBAND: groups['supervisor sideband'].append((ball, n))
        elif n.startswith('PHY_') and n in ('PHY_RESET_N', 'PHY_INT_N'): groups['PHY control'].append((ball, n))
        elif n.startswith('PHY_'): groups['RGMII'].append((ball, n))
        elif n.startswith('LINK_'): groups['links'].append((ball, n))
        elif n == 'SYS_CLK': groups['system clock'].append((ball, n))
        elif n.startswith('HDMI_'): groups['HDMI'].append((ball, n))
        else: raise ValueError(f'Unclassified allocated net: {ball} {n}')
    assert len(groups['supervisor sideband']) == len(sb) == len(SIDEBAND)
    assert sum(map(len, groups.values())) == len(net)

    W("## Config flash and strap\n")
    W("| Ball | Net | Package name |")
    W("|---|---|---|")
    for ball, n in CONFIG_USE.items(): W(f"| {ball} | `{n}` | {names.get(ball,'')} |")
    W("\n`CCLK`, `PROGRAM_B`, `INIT_B`, `DONE`, `M[2:0]` and JTAG are bank 0")
    W("dedicated pins — see the bank 0 table below.\n")

    W("## System clock\n")
    W("| Ball | Net | Package name |")
    W("|---|---|---|")
    for ball, n in groups['system clock']: W(f"| {ball} | `{n}` | {names[ball]} |")
    W("\nX4, 50 MHz CMOS, on an MRCC P ball so it reaches the bank's MMCMs; the")
    W("pair's N ball is left free.\n")
    W("## PSRAM — four independent QSPI buses, bank 13 at 1.8 V\n")
    W("| Chip | SCK | CE# | IO0 | IO1 | IO2 | IO3 |")
    W("|---|---|---|---|---|---|---|")
    for c, balls in psram.items(): W(f"| PSRAM{c} | " + " | ".join(balls) + " |")
    W("\nEach chip's six lines come from three adjacent differential pairs, so the")
    W("group stays physically tight and length matching stays local. Both MRCC")
    W("pairs of the bank (U21/V21, U22/V22) are left free.\n")
    W("## SDRAM — W9825G6KH-6, data in bank 35, address in bank 14\n")
    W("| Ball | Net | Package name |")
    W("|---|---|---|")
    for ball, n in groups['SDRAM']: W(f"| {ball} | `{n}` | {names[ball]} |")
    W("\nCLK is an output on a plain ball (no MRCC/SRCC), through 22 ohm; CS and CKE")
    W("are plain I/O with no configuration function. The address balls are the")
    W("block of columns 23-26, rows M-T, that the PSRAMs left.\n")
    W("## MRAM — MR25H10CDF, bank 14\n")
    W("| Ball | Net | Package name |")
    W("|---|---|---|")
    for ball, n in groups['MRAM']: W(f"| {ball} | `{n}` | {names[ball]} |")
    W("")
    W("## microSD — SPI mode, bank 14\n")
    W("| Ball | Net | Package name |")
    W("|---|---|---|")
    for ball, n in groups['microSD']: W(f"| {ball} | `{n}` | {names[ball]} |")
    W("\nSD_CD is the socket's detect switch, read with the FPGA's pull-up.\n")

    W("## Supervisor sideband\n")
    W("| Ball | Net |")
    W("|---|---|")
    for b, n in zip(sb, SIDEBAND): W(f"| {b} | `{n}` |")
    W("")

    W("## Extension slots\n")
    W("Direct slots A-H expose twelve ordinary numbered I/O as six adjacent")
    W("differential-capable pairs. Pairing remains")
    W("an optional capability rather than part of the basic connector UX.")
    W("5V BUS 0 and 5V BUS 1 each expose one complete translated 8-bit bus.\n")
    W("| Slot | Bank | FPGA balls in connector order |")
    W("|---|---|---|")
    for s, (bk, prs) in slots.items():
        W(f"| **{s}** | {bk} | " + ", ".join(b for pr in prs for b in pr) + " |")
    W("")
    dirs = groups['5V bus direction']
    W(f"The two 5V buses are buffered; A-H are direct. "
      f"{', '.join(b for b, _ in dirs)} are their direction controls. "
      f"Together the buses cost **20** FPGA I/O for 16 connector signals.\n")
    W("| Bus control | FPGA ball | Bank | Default |")
    W("|---|---|---|---|")
    for ball, n in groups['5V bus enable']:
        bank = '14' if n.startswith('BUS5V0') else '13'
        W(f"| `{n}` | {ball} | {bank} | 10k to +3V3; high disables the bus |")
    W("\nHold OE_N high while setting DIR and data; drive OE_N low only when ready.")
    W("Raise OE_N again before changing direction.\n")

    W("## Bank 0 — dedicated configuration pins\n")
    W("| Ball | Name |")
    W("|---|---|")
    for ball, name in sorted(other['0']): W(f"| {ball} | `{name}` |")
    W("")
    W("## Network: bank 16 at 2.5 V\n")
    W("RGMII and MDIO to the RTL8211FD-CG (DVDD_RG = +2V5). `PHY_RXC` is the")
    W("PHY's 125 MHz receive clock on an MRCC ball; the two link receive clocks")
    W("sit on clock-capable pairs (MRCC for P, SRCC for Q). See `ref/network.md`")
    W("and `ref/link-ports.md`.\n")
    W("| Ball | Net | Package name |")
    W("|---|---|---|")
    for ball, n in sorted(groups['RGMII'], key=lambda t: t[1]): W(f"| {ball} | `{n}` | {names[ball]} |")
    W("")
    W("| Port | Pair | P | N | Package name |")
    W("|---|---|---|---|---|")
    for port, prs in assign.link.items():
        for name, (pb, nb) in prs.items():
            W(f"| LINK {port} | {name} | {pb} | {nb} | {names[pb]} |")
    W("")
    W("The two 3.3 V PHY pins are in bank 13:\n")
    W("| Ball | Net | Package name |")
    W("|---|---|---|")
    for ball, n in groups['PHY control']: W(f"| {ball} | `{n}` | {names[ball]} |")
    W("")
    W("## Video: bank 35 at 3.3 V\n")
    W("HDMI out. The four lanes are TMDS_33 pairs, terminated by the monitor's")
    W("50 ohm pull-ups to 3.3 V; the six control lines go to U31 (TPD12S016),")
    W("which shifts DDC and CEC to the cable's 5 V. All fourteen balls sit in")
    W("the package's two outer rows.\n")
    W("| Pair | P | N | Package name |")
    W("|---|---|---|---|")
    for name, (pb, nb) in assign.hdmi.items():
        W(f"| {name} | {pb} | {nb} | {names[pb]} |")
    W("")
    W("| Ball | Net | Package name |")
    W("|---|---|---|")
    for ball, n in sorted(groups['HDMI'], key=lambda t: t[1]):
        if not n.endswith(('_P', '_N')): W(f"| {ball} | `{n}` | {names[ball]} |")
    W("")
    W("## GTP banks 213 and 216 — unused, powered\n")
    W("Rev A has no transceiver load. Both quads keep MGTAVCC/MGTAVTT powered,")
    W("all RX pins to GND, TX and reference-clock pins floating, and one 100 ohm")
    W("1% RCAL each to +1V2_MGT (UG482 Tables 5-5/5-6).\n")
    W("| Ball | Name |")
    W("|---|---|")
    for ball, name in sorted(other['216']) + sorted(other['213']): W(f"| {ball} | `{name}` |")
    W("")

    W("## Budget\n")
    for k in ('slots', 'PSRAM', 'SDRAM', 'MRAM', 'microSD', 'supervisor sideband', 'config flash + strap',
              '5V bus data', '5V bus direction', '5V bus enable'):
        W(f"- {k}: **{len(groups[k])}**")
    W(f"- **assigned HR I/O: {len(net)} of {tot}**")
    W(f"- **free: {tot - len(net)}** for base-board peripherals")
    rendered = "\n".join(o) + "\n"
    if '--write' in sys.argv:
        with open('ref/ballmap.md', 'w', encoding='utf-8') as f:
            f.write(rendered)
        print('wrote ref/ballmap.md')
    else:
        print(rendered, end='')

main()
