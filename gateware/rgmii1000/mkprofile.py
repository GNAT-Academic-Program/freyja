#!/usr/bin/env python3
"""Writes the 125 MHz DDR RGMII profile: top.v, rgmii1000_pins.xdc, rgmii1000_timing.xdc.

    python3 gateware/rgmii1000/mkprofile.py [outdir] [--no-board] [--drive 8] [--slew FAST] [--taps 11] [--data-slew SLOW]

Pins and I/O standards come from ref/freya.xdc, routed delays from data/route.json
(route.py on the routed board), PHY timing from RTL8211F rev 1.7 Table 60. Nothing
in tools/ or gateware/gate reads this directory; the allocation gate is unchanged.
--no-board leaves the board terms at zero: the FPGA-only run that sets the routing limits.
"""
import argparse
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
XDC = os.path.join(HERE, '..', '..', 'ref', 'freya.xdc')

T = 8.0                 # 1000 Mb/s, Table 60 typical
# TXDLY = 1: U30 delays TXC inside itself, so the FPGA drives edge-aligned and sends no shifted clock. The binding row
# is TskewT, "without delay integrated", held here at U30's pins. The internal 2 ns is not added anywhere: Realtek gives
# no tolerance for it and no input window in this mode, so this limit is a reading, not a guarantee. See README.md.
T_SKEW_T = 0.5
# RXDLY = 1: U30 is the transmitter "with delay integrated", guaranteed at its pins.
T_SETUP_T, T_HOLD_T = 1.2, 1.2
# U30 driving the real line against its unstated test load: no RTL8211F IBIS model exists. An allowance, both ways.
RX_ALLOWANCE = 0.1
TX = ['PHY_TXD0', 'PHY_TXD1', 'PHY_TXD2', 'PHY_TXD3', 'PHY_TX_CTL']
RX = ['PHY_RXD0', 'PHY_RXD1', 'PHY_RXD2', 'PHY_RXD3', 'PHY_RX_CTL']


def board_terms():
    """Per-net (lo, hi) of data minus clock at the receiver, ns. RX adds the allowance both ways."""
    r = json.load(open(os.path.join(HERE, 'data', 'route.json')))
    tx = {n: (r['tx'][n]['lo'], r['tx'][n]['hi']) for n in TX}
    rx = {n: (r['rx'][n]['lo'] - RX_ALLOWANCE, r['rx'][n]['hi'] + RX_ALLOWANCE) for n in RX}
    return tx, rx


def top_v(taps):
    """Registered DDR in the IOBs only. TXC is an ODDR on the same clock as the data, no phase
    shift. RX has only its received clock: IBUF, BUFIO for the IDDRs, BUFR for the fabric, and a
    fixed IDELAY on each data ball, because BUFIO insertion delay puts the clock past the window.
    An LFSR keeps every register observable. This is a timing fixture, not a MAC."""
    v = f'''// Timing fixture for U30 at 125 MHz DDR. Generated by mkprofile.py. Not a MAC.
module top(input SYS_CLK, output PHY_TXC, {", ".join("output " + n for n in TX)},
 input PHY_RXC, {", ".join("input " + n for n in RX)});
 wire fb, fbb, c125_u, c125, c200_u, c200, lock, rxc_i, rxc_io, rxc_r, dly_rdy;
 MMCME2_BASE #(.CLKIN1_PERIOD(20.0), .CLKFBOUT_MULT_F(20.0), .DIVCLK_DIVIDE(1), .CLKOUT0_DIVIDE_F(8.0), .CLKOUT1_DIVIDE(5))
  mmcm(.CLKIN1(SYS_CLK), .CLKFBIN(fbb), .CLKFBOUT(fb), .CLKOUT0(c125_u), .CLKOUT1(c200_u), .LOCKED(lock), .PWRDWN(1'b0), .RST(1'b0));
 BUFG bfb(.I(fb), .O(fbb));
 BUFG b125(.I(c125_u), .O(c125));
 BUFG b200(.I(c200_u), .O(c200));
 (* IODELAY_GROUP = "rgmii" *) IDELAYCTRL dctl(.REFCLK(c200), .RST(!lock), .RDY(dly_rdy));
 ODDR #(.DDR_CLK_EDGE("SAME_EDGE"), .SRTYPE("SYNC"))
  txc_oddr(.C(c125), .CE(1'b1), .D1(1'b1), .D2(1'b0), .Q(PHY_TXC), .R(1'b0), .S(1'b0));
 reg [31:0] lfsr = 32'h1;
 always @(posedge c125) lfsr <= {{lfsr[30:0], lfsr[31]^lfsr[21]^lfsr[1]^lfsr[0]^dly_rdy}};
'''
    for i, n in enumerate(TX):
        v += (f' ODDR #(.DDR_CLK_EDGE("SAME_EDGE"), .SRTYPE("SYNC"))\n'
              f'  tx{i}(.C(c125), .CE(1\'b1), .D1(lfsr[{i*5}]), .D2(lfsr[{i*5+2}]), .Q({n}), .R(1\'b0), .S(1\'b0));\n')
    v += ''' IBUF rxc_ibuf(.I(PHY_RXC), .O(rxc_i));
 BUFIO rxc_bufio(.I(rxc_i), .O(rxc_io));
 BUFR #(.BUFR_DIVIDE("BYPASS")) rxc_bufr(.I(rxc_i), .CE(1'b1), .CLR(1'b0), .O(rxc_r));
'''
    v += f' wire [{len(RX)*2-1}:0] rx_w;\n wire [{len(RX)-1}:0] rx_d;\n (* dont_touch="true" *) reg [{len(RX)*2-1}:0] rx_q = 0;\n'
    v += ' always @(posedge rxc_r) rx_q <= rx_w;\n'
    for i, n in enumerate(RX):
        v += (f' (* IODELAY_GROUP = "rgmii" *) IDELAYE2 #(.IDELAY_TYPE("FIXED"), .IDELAY_VALUE({taps}), .DELAY_SRC("IDATAIN"), .REFCLK_FREQUENCY(200.0), .HIGH_PERFORMANCE_MODE("TRUE"), .SIGNAL_PATTERN("DATA"))\n'
              f'  dly{i}(.IDATAIN({n}), .DATAOUT(rx_d[{i}]), .C(1\'b0), .CE(1\'b0), .INC(1\'b0), .LD(1\'b0), .LDPIPEEN(1\'b0), .REGRST(1\'b0), .CINVCTRL(1\'b0), .CNTVALUEIN(5\'b0), .DATAIN(1\'b0));\n'
              f' IDDR #(.DDR_CLK_EDGE("SAME_EDGE_PIPELINED"), .SRTYPE("SYNC"))\n'
              f'  rx{i}(.C(rxc_io), .CE(1\'b1), .D(rx_d[{i}]), .Q1(rx_w[{i*2}]), .Q2(rx_w[{i*2+1}]), .R(1\'b0), .S(1\'b0));\n')
    return v + 'endmodule\n'


def pins_xdc():
    keep = [l.rstrip() for l in open(XDC)
            if 'PACKAGE_PIN' in l and re.search(r'get_ports \{(PHY_T\w+|PHY_RX\w+|SYS_CLK)\}', l)]
    return '# Excerpt of ref/freya.xdc for this fixture only. A real design reads ref/freya.xdc instead.\n' + '\n'.join(keep) + '\n'


def timing_xdc(tx, rx, drive, slew, data_slew=None):
    bus = ' '.join(['PHY_TXC'] + TX)
    x = [
        '# RGMII profile, 125 MHz DDR, U30 RTL8211FDI-CG, TXDLY = 1, RXDLY = 1. Generated by mkprofile.py.',
        '# Holds only with the matching RTL: see README.md. After rerouting, rerun; do not edit numbers.',
        'create_clock -period 20.000 -name sys_clk [get_ports SYS_CLK]',
        '# X4 C717684: no datasheet in the repository. 200 ps peak to peak is an assumption, as in sdram100.',
        'set_input_jitter sys_clk 0.200',
        f'set_property DRIVE {drive} [get_ports {{{bus}}}]',
        f'set_property SLEW {slew} [get_ports {{{bus}}}]',
        *([f'set_property SLEW {data_slew} [get_ports {{{" ".join(TX)}}}]'] if data_slew else []),
        '# TX: skew-based, edge-aligned at the FPGA, both TXC edges. Data launched on a TXC edge must reach U30 within',
        '# TskewT of that same edge. The half-cycle setup relation exists only to express the limit: setup slack = TskewT - skew.',
        'create_generated_clock -name txc -source [get_pins txc_oddr/C] -divide_by 1 [get_ports PHY_TXC]',
    ]
    for n in TX:
        lo, hi = tx[n]
        x.append(f'set_output_delay -clock txc -max {T/2-T_SKEW_T+hi:.3f} [get_ports {n}]')
        x.append(f'set_output_delay -clock txc -min {T_SKEW_T+lo:.3f} [get_ports {n}]')
        x.append(f'set_output_delay -clock txc -clock_fall -max {T/2-T_SKEW_T+hi:.3f} [get_ports {n}] -add_delay')
        x.append(f'set_output_delay -clock txc -clock_fall -min {T_SKEW_T+lo:.3f} [get_ports {n}] -add_delay')
    x += ['# RX: the received clock only. Data launched by one RXC edge is valid TholdT after it and TsetupT before the next,',
          '# at U30. max = T/2 - TsetupT + (data - clock) high; min = TholdT + (data - clock) low. No jitter term: Table 60 gives none.',
          f'create_clock -period {T:.3f} -name phy_rxc [get_ports PHY_RXC]']
    for n in RX:
        lo, hi = rx[n]
        x.append(f'set_input_delay -clock phy_rxc -max {T/2-T_SETUP_T+hi:.3f} [get_ports {n}]')
        x.append(f'set_input_delay -clock phy_rxc -min {T_HOLD_T+lo:.3f} [get_ports {n}]')
        x.append(f'set_input_delay -clock phy_rxc -clock_fall -max {T/2-T_SETUP_T+hi:.3f} [get_ports {n}] -add_delay')
        x.append(f'set_input_delay -clock phy_rxc -clock_fall -min {T_HOLD_T+lo:.3f} [get_ports {n}] -add_delay')
    x += ['# The two clocks share no reference on the board. The fixture has no path between them.',
          'set_clock_groups -asynchronous -group [get_clocks -include_generated_clocks sys_clk] -group phy_rxc']
    return '\n'.join(x) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('outdir', nargs='?', default=HERE)
    ap.add_argument('--no-board', action='store_true')
    ap.add_argument('--drive', type=int, default=8)
    ap.add_argument('--slew', default='FAST')
    ap.add_argument('--taps', type=int, default=11)
    ap.add_argument('--data-slew', default=None, help='TX data slew, when it differs from TXC')
    a = ap.parse_args()
    os.makedirs(a.outdir, exist_ok=True)
    if a.no_board:
        tx, rx = {n: (0., 0.) for n in TX}, {n: (0., 0.) for n in RX}
    else:
        tx, rx = board_terms()
    open(os.path.join(a.outdir, 'top.v'), 'w').write(top_v(a.taps))
    open(os.path.join(a.outdir, 'rgmii1000_pins.xdc'), 'w').write(pins_xdc())
    open(os.path.join(a.outdir, 'rgmii1000_timing.xdc'), 'w').write(timing_xdc(tx, rx, a.drive, a.slew, a.data_slew))


if __name__ == '__main__':
    main()
