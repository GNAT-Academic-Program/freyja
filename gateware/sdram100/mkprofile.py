#!/usr/bin/env python3
"""Writes the 100 MHz / CL3 SDRAM profile: top.v, sdram100_pins.xdc, sdram100_timing.xdc.

    python3 gateware/sdram100/mkprofile.py [outdir] [--phase 270] [--no-mcp]

Pins and I/O standards come from ref/freya.xdc, flight times from
data/flight_8.json (flight.py on the routed board), package delay from
data/pkg_delay.csv, memory timing from the datasheet. Nothing in tools/ or
gateware/gate reads this directory; the allocation gate is unchanged.
"""
import argparse
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
XDC = os.path.join(HERE, '..', '..', 'ref', 'freya.xdc')

# W9825G6KH rev A03, section 9.5, -6 column, CL3 (ns).
T_SETUP, T_HOLD, T_AC, T_OH = 1.5, 0.8, 5.0, 3.0
# ps/mm from fieldsolve.py; via barrels in ps between the layer pairs.
PS_PER_MM = {'F.Cu': 5.88, 'B.Cu': 5.88, 'In2': 6.97, 'In5': 6.97}
VIA_PS = {'F.Cu-In2': 1.6, 'F.Cu-In5': 9.3, 'B.Cu-F.Cu': 10.9, 'In2-In5': 7.7, 'B.Cu-In5': 1.7}
PROPAGATION_SPREAD = 0.05   # Dk and geometry on propagation delay
# U32 output into the real line against its 30 pF AC test load, and input
# threshold 1.65 V against 1.4 V. An allowance: no U32 IBIS model is available.
READ_ALLOWANCE = 0.3

DQ = [f'SDRAM_DQ{i}' for i in range(16)]
OUTS = [f'SDRAM_A{i}' for i in range(13)] + [
    'SDRAM_BA0', 'SDRAM_BA1', 'SDRAM_CS_N', 'SDRAM_RAS_N', 'SDRAM_CAS_N',
    'SDRAM_WE_N', 'SDRAM_CKE', 'SDRAM_LDQM', 'SDRAM_UDQM']


def package_delays():
    out = {}
    for line in open(os.path.join(HERE, 'data', 'pkg_delay.csv')):
        if not line.startswith('#'):
            ball, lo, hi = line.strip().split(',')
            out[ball] = (float(lo) / 1000, float(hi) / 1000)
    return out


def line_delay(net):
    ps = sum(VIA_PS[v] if k == 'via' else v * PS_PER_MM[k] for k, v in net['sections'])
    return ps / 1000


def budget():
    """Per-net output and input delays in ns."""
    flight = json.load(open(os.path.join(HERE, 'data', 'flight_8.json')))
    pkg = package_delays()
    clock = flight['SDRAM_CLK']['sim']
    dc = [clock[c]['r']['flight'] for c in clock]
    dc_min, dc_max = min(dc), max(dc)
    rows = []
    for name, net in sorted(flight.items()):
        if name == 'SDRAM_CLK':
            continue
        sim = net['sim']
        settle = max(sim[c][e]['settle'] for c in sim for e in 'rf')
        leave = min(sim[c][e]['leave'] for c in sim for e in 'rf')
        row = dict(net=name, settle=settle, leave=leave,
                   omax=T_SETUP + settle - dc_min, omin=-T_HOLD + leave - dc_max)
        if name in DQ:
            lo, hi = pkg[net['ball']]
            line = line_delay(net)
            q_max = hi + line * (1 + PROPAGATION_SPREAD) + .01
            q_min = lo + line * (1 - PROPAGATION_SPREAD) - .01
            row.update(q_max=q_max, q_min=q_min,
                       imax=dc_max + T_AC + q_max + READ_ALLOWANCE,
                       imin=dc_min + T_OH + q_min - READ_ALLOWANCE)
        rows.append(row)
    return dict(dc_min=dc_min, dc_max=dc_max, rows=rows)


def top_v(phase):
    """Registered I/O in the IOBs, forwarded clock from an ODDR, one MMCM. The
    forwarded phase is a real MMCM output, so the XDC derives it from the
    netlist rather than stating a waveform. An LFSR keeps every register
    observable. This is a timing fixture, not a controller."""
    mix = lambda i, k: f'lfsr[{(i*3+k)%64}]^lfsr[{(i*7+13+k)%64}]^lfsr[{(i*11+29+k)%64}]'
    v = f'''// Timing fixture for U32 at 100 MHz, CL3. Generated by mkprofile.py. Not a controller.
module top(input SYS_CLK, output SDRAM_CLK,
 {", ".join("output " + o for o in OUTS)},
 {", ".join("inout " + d for d in DQ)});
 wire fb, fbb, c0, c1, clk_sys, clk_fwd, lock;
 MMCME2_BASE #(.CLKIN1_PERIOD(20.0), .CLKFBOUT_MULT_F(20.0), .DIVCLK_DIVIDE(1), .CLKOUT0_DIVIDE_F(10.0),
  .CLKOUT1_DIVIDE(10), .CLKOUT1_PHASE({phase:.3f}))
  mmcm(.CLKIN1(SYS_CLK), .CLKFBIN(fbb), .CLKFBOUT(fb), .CLKOUT0(c0), .CLKOUT1(c1), .LOCKED(lock), .PWRDWN(1'b0), .RST(1'b0));
 BUFG bfb(.I(fb), .O(fbb));
 BUFG b0(.I(c0), .O(clk_sys));
 BUFG b1(.I(c1), .O(clk_fwd));
 ODDR #(.DDR_CLK_EDGE("OPPOSITE_EDGE"), .SRTYPE("SYNC"))
  fwd(.C(clk_fwd), .CE(1'b1), .D1(1'b1), .D2(1'b0), .Q(SDRAM_CLK), .R(1'b0), .S(1'b0));
 reg [63:0] lfsr = 64'h1;
 (* dont_touch="true" *) reg [{len(OUTS)-1}:0] o_r = 0;
 (* dont_touch="true" *) reg [15:0] dq_o = 0, dq_t = 16'hffff, dq_i = 0;
 reg [15:0] dq_s = 0;
 wire [15:0] dq_w;
 wire fold = ^dq_s;
 always @(posedge clk_sys) begin
  lfsr <= {{lfsr[62:0], lfsr[63]^lfsr[62]^lfsr[60]^lfsr[59]^fold^lock}};
'''
    for i in range(len(OUTS)):
        v += f'  o_r[{i}] <= {mix(i, 1)};\n'
    for i in range(16):
        v += f'  dq_o[{i}] <= {mix(i, 5)}^dq_s[{i}]; dq_t[{i}] <= {mix(i, 9)};\n'
    v += '  dq_s <= dq_i;\n  dq_i <= dq_w;\n end\n'
    for i, o in enumerate(OUTS):
        v += f' assign {o} = o_r[{i}];\n'
    for i, d in enumerate(DQ):
        v += f' IOBUF io{i}(.I(dq_o[{i}]), .T(dq_t[{i}]), .O(dq_w[{i}]), .IO({d}));\n'
    return v + 'endmodule\n'


def pins_xdc():
    lines = [l.rstrip() for l in open(XDC)]
    keep = [l for l in lines if re.search(r'get_ports \{(SDRAM_\w+|SYS_CLK)\}', l)]
    return '# Excerpt of ref/freya.xdc for this fixture only. A real design reads ref/freya.xdc instead.\n' + '\n'.join(keep) + '\n'


def timing_xdc(mcp):
    b = budget()
    bus = ' '.join(OUTS + DQ)
    x = [
        '# SDRAM profile, 100 MHz, CL3, U32 W9825G6KH-6. Generated by mkprofile.py from the routed board at 8cbbd79.',
        '# Holds only with the matching RTL: see README.md. Above 100 MHz or after rerouting, rerun; do not edit numbers.',
        'create_clock -period 20.000 -name sys_clk [get_ports SYS_CLK]',
        '# X4 C717684: no datasheet in the repository. 200 ps peak to peak is an assumption, not a measured figure.',
        'set_input_jitter sys_clk 0.200',
        '# The phase comes from the MMCM output driving fwd/C; this line states no waveform of its own.',
        'create_generated_clock -name sdram_clk -source [get_pins fwd/C] -divide_by 1 [get_ports SDRAM_CLK]',
        '# Bus 8 mA slow, registers in the IOBs. SDRAM_CLK keeps 12 mA fast from ref/freya.xdc and runs through R151.',
        f'set_property DRIVE 8 [get_ports {{{bus}}}]',
        'set_property SLEW SLOW [get_ports {%s}]' % bus,
        f'set_property IOB TRUE [get_ports {{{bus}}}]',
        '# output delay: max = tS + settle - clock flight min; min = -tH + leave - clock flight max.',
        '# input delay: max = clock flight max + tAC + DQ delay max + allowance; min = clock flight min + tOH + DQ delay min - allowance.',
    ]
    for r in b['rows']:
        n = r['net']
        x.append(f'set_output_delay -clock sdram_clk -max {r["omax"]:.3f} [get_ports {n}]')
        x.append(f'set_output_delay -clock sdram_clk -min {r["omin"]:.3f} [get_ports {n}]')
        if 'imax' in r:
            x.append(f'set_input_delay -clock sdram_clk -max {r["imax"]:.3f} [get_ports {n}]')
            x.append(f'set_input_delay -clock sdram_clk -min {r["imin"]:.3f} [get_ports {n}]')
    if mcp:
        x += ['# Read capture: launch at sdram_clk rise T, capture at c0 edge T + 12.5 ns, the edge the read-latency counter accepts.',
              '# Setup is checked against that word. Vivado then places hold on c0 edge T + 2.5 ns: the word launched at T against the',
              '# capture of the word before it. That is the real next-word check, so there is no -hold: -hold 1 would compare a word',
              '# launched one period later and check nothing. Scoped to the capture flops, so any other reader of DQ stays at one cycle.',
              'set_multicycle_path -setup 2 -from [get_clocks sdram_clk] -to [get_cells {dq_i_reg[*]}]']
    return '\n'.join(x) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('outdir', nargs='?', default=HERE)
    ap.add_argument('--phase', type=float, default=270.)
    ap.add_argument('--no-mcp', action='store_true')
    a = ap.parse_args()
    os.makedirs(a.outdir, exist_ok=True)
    open(os.path.join(a.outdir, 'top.v'), 'w').write(top_v(a.phase))
    open(os.path.join(a.outdir, 'sdram100_pins.xdc'), 'w').write(pins_xdc())
    open(os.path.join(a.outdir, 'sdram100_timing.xdc'), 'w').write(timing_xdc(not a.no_mcp))


if __name__ == '__main__':
    main()
